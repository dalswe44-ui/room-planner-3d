// 사진이나 손그림 배치도(굿노트 등)를 AI에게 보여 주고, AI가 아래 JSON을 돌려주면
// 사용자가 앱에 붙여 넣고 미리보기를 확인한 뒤 적용한다. 앱은 사진에서 치수를 뽑지 않는다.
// 2026-11-17: 적힌 숫자가 우선이고, 적히지 않은 위치·한쪽 길이는 AI가 그림의 비율로 어림해 notes에 밝힌다(사용자 요청: 그린 배치 그대로).

/** 배치도 JSON의 길이 단위. 값은 모두 이 단위의 숫자다. */
export type LayoutUnit = 'mm' | 'cm' | 'm';

export interface LayoutImportItem {
  name: string;
  /** 회전 0일 때 가로(왼쪽-오른쪽) 길이. 그림에 없으면 null */
  w: number | null;
  /** 회전 0일 때 세로(위-아래) 길이. 그림에 없으면 null */
  d: number | null;
  /** 높이. 그림에 없으면 null */
  h: number | null;
  /** 왼쪽 벽에서 가구 왼쪽 변까지. 그림에 없으면 null */
  left: number | null;
  /** 위쪽 벽에서 가구 위쪽 변까지. 그림에 없으면 null */
  top: number | null;
  /** 0, 90, 180, 270. 그림에 없으면 0 */
  rotationDeg: 0 | 90 | 180 | 270;
}

export interface LayoutImport {
  format: 'room-layout';
  version: 1;
  /** AI가 그림에서 옮겨 적은 숫자와 그 뜻. 값을 정하기 전에 먼저 쓰게 해서 잘못 읽는 일을 줄인다. 앱은 쓰지 않는다. */
  readings?: string[];
  unit: LayoutUnit;
  room: {
    /** 가로(왼쪽 벽 ~ 오른쪽 벽) */
    width: number;
    /** 세로(위쪽 벽 ~ 아래쪽 벽) */
    depth: number;
    /** 천장 높이. 그림에 없으면 null */
    height: number | null;
  };
  items: LayoutImportItem[];
  /** AI가 읽지 못했거나 추정한 부분. 사용자에게 그대로 보여 준다. */
  notes: string[];
}

/** 사용자가 배치도 사진과 함께 AI에게 줄 프롬프트. 앱의 "프롬프트 복사" 버튼이 이 문자열을 복사한다. */
export const LAYOUT_READER_PROMPT = `첨부한 그림은 방의 배치도(평면도)입니다. 손으로 그렸거나 필기 앱 화면을 찍은 것일 수 있습니다.
그림을 읽어 아래 형식의 JSON 하나만 돌려주세요. 설명 문장은 쓰지 마세요.

읽는 순서
A. 필기 앱의 도구 막대, 상태 표시줄 같은 화면 요소는 무시합니다. 가장 바깥의 큰 사각형이 방입니다.
B. 그림에 적힌 숫자를 하나도 빠뜨리지 말고 먼저 readings에 옮겨 적습니다. 한 줄에 하나씩 "적힌 글자 → 무엇의 길이인지"를 씁니다. 숫자 옆의 굽은 선이나 괄호 모양 선은 그 숫자가 재는 구간의 양 끝을 가리킵니다.
C. 손글씨 숫자는 헷갈리기 쉽습니다(7과 1·4·n, 5와 6·S, 0과 6 등). 읽은 값이 그림과 맞는지 반드시 대조합니다: 방 가로·세로 숫자의 비가 그려진 사각형의 가로·세로 비와 비슷한지, 가구가 방 안에 들어가는지, 벽을 따라 놓인 가구들의 길이 합이 그 벽 길이를 넘지 않는지. 맞지 않으면 다른 숫자로 읽을 수 있는지 다시 보고, 그림과 가장 잘 맞는 읽기를 고른 뒤 notes에 적습니다.
D. 그런 다음 room과 items를 채웁니다.

규칙
1. 그림에 숫자로 적힌 길이는 그 값을 그대로 씁니다. 적힌 숫자가 그려진 크기와 달라도 적힌 숫자가 우선입니다.
2. 단위는 그림에 적힌 단위를 따르고 unit에 "mm", "cm", "m" 중 하나로 적습니다. JSON의 모든 길이는 그 단위 하나의 숫자로만 적습니다. 단위가 섞여 있으면 unit으로 바꿔 씁니다(예: unit이 "m"인데 60cm라고 적혀 있으면 0.6). 단위 글자가 없는 숫자는 같은 그림의 다른 숫자와 같은 단위로 봅니다. 단위가 전혀 없으면 숫자의 크기로 판단하고(예: 방 폭이 360이면 cm) notes에 적습니다.
3. 그림을 위에서 내려다본 그대로 둡니다. room.width는 그림의 가로(왼쪽 벽~오른쪽 벽), room.depth는 세로(위쪽 벽~아래쪽 벽)입니다. 가구의 w는 그림에서 가로 방향 길이, d는 세로 방향 길이입니다. rotationDeg는 0으로 둡니다.
4. 가구의 가로·세로 중 한쪽만 적혀 있으면, 적히지 않은 쪽은 그려진 모양의 가로세로 비와 적힌 쪽의 값으로 어림해 적고 notes에 "어림"이라고 적습니다. 둘 다 적혀 있지 않으면 방 크기와 그려진 비율로 어림하고 notes에 적습니다. 어림할 수 없을 때만 null로 둡니다. 높이 h는 적혀 있지 않으면 null입니다.
5. 가구의 위치는 left(왼쪽 벽에서 가구 왼쪽 변까지)와 top(위쪽 벽에서 가구 위쪽 변까지)으로 적습니다. 다음 순서로 정합니다.
   (가) 벽에서의 거리가 숫자로 적혀 있으면 그 값. 오른쪽 벽이나 아래쪽 벽에서 잰 값이면 방 크기에서 빼서 바꿉니다.
   (나) 가구의 변이 벽선에 붙어 그려져 있으면 그 벽까지의 거리는 0. 오른쪽 벽에 붙어 있으면 left = room.width - w, 아래쪽 벽에 붙어 있으면 top = room.depth - d.
   (다) 그 밖에는 그림에서 가구가 놓인 자리의 비율로 어림합니다(예: 가구 왼쪽 변이 방 가로의 40% 지점이면 left = room.width × 0.4). 어림한 값은 notes에 적습니다.
   left와 top은 되도록 null로 두지 않습니다. 가구가 방 밖으로 나가지 않게 합니다.
6. 가구 이름은 그림에 적힌 그대로 짧게 씁니다(예: "침대", "TV", "화장대"). 읽기 어려우면 가장 그럴듯한 이름 하나만 name에 쓰고, 불확실하다는 말은 notes에 씁니다. name에 괄호나 설명을 넣지 않습니다.
7. 벽 모서리나 벽선에 그려진 부채꼴(문이 열리는 자리)과 벽의 틈은 문입니다. 가구로 넣지 말고 notes에 "문: 어느 벽 어디쯤"이라고만 적습니다.
8. 방이 직사각형이 아니면 바깥을 감싸는 직사각형으로 적고 notes에 적습니다.
9. 읽기 어려운 글자, 서로 맞지 않는 치수, 어림한 값은 모두 notes에 한 줄씩 적습니다.

형식
{
  "format": "room-layout",
  "version": 1,
  "readings": ["위쪽 3.6m → 방 가로", "침대 옆 2m → 침대 세로"],
  "unit": "m",
  "room": { "width": 3.6, "depth": 3, "height": null },
  "items": [
    { "name": "침대", "w": 1, "d": 2, "h": null, "left": 0, "top": 0, "rotationDeg": 0 }
  ],
  "notes": []
}`;
